OPTIONAL = {"status_notes": None, "visionos_min": None, "input": [], "tags": [], "description": None,
            "credits": [], "upstream": [], "source_ref": None,
            "experiences": [], "install": ["build"]}


class BrandError(RuntimeError):
    pass


def md(value: object, limit: int = 300) -> str:
    """Escape contributor text for Markdown files (mentions in files never notify)."""
    text = "" if value is None else " ".join(str(value).split())
    if len(text) > limit:
        text = text[: limit - 1] + "…"
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return re.sub(r"([\\`*_{}\[\]()#+!|~])", r"\\\1", text)


def attr(value: object, limit: int = 300) -> str:
    """Escape text for an HTML attribute in a Markdown file."""
    text = "" if value is None else " ".join(str(value).split())
    if len(text) > limit:
        text = text[: limit - 1] + "…"
    return html.escape(text, quote=True)


def _env(root: Path) -> jinja2.Environment:
    env = jinja2.Environment(loader=jinja2.FileSystemLoader(str(root / "templates")),
                             autoescape=False, keep_trailing_newline=True,
                             trim_blocks=True, lstrip_blocks=True, undefined=jinja2.StrictUndefined)
    env.filters["md"] = md
    env.filters["attr"] = attr
    return env


def _date(value: str | None) -> str:
    return value[:10] if value else ""


# --- view model ---------------------------------------------------------------------

def brand_lines(brand: dict) -> dict:
    site = brand["site"]
    site_label = re.sub(r"^https?://", "", site).rstrip("/")
    return {
        "curated_line": f"Curated by {brand['curator_name']} ([@{brand['curator_github']}]"
                        f"(https://github.com/{brand['curator_github']})) · [{site_label}]({site})",
        "footer": f"Curated by trevorbilt · [{site_label}]({site})",
        "site_label": site_label,
    }


def brand_block(root: Path, brand: dict) -> str:
    lines = [BRAND_START]
    logo = str(brand.get("logo") or "")
    if logo.startswith("https://") or (logo and (root / logo).is_file()):
        lines += [f'<img src="{logo}" alt="Trevorbilt" width="200">', ""]
    lines += [f"# {brand['display_name']}", "", brand_lines(brand)["curated_line"], BRAND_END]
    return "\n".join(lines)


def developer_plain(entry: dict) -> str:
    """The developer as plain text, for the Unavailable ports record (no links)."""
    dev = entry.get("developer") or {}
    return f"{md(dev['name'], 80)} (@{dev['github']})" if dev.get("name") else f"@{dev['github']}"


def developer_display(entry: dict) -> str:
    dev = entry.get("developer") or {}
    handle = f"[@{dev['github']}](https://github.com/{dev['github']})"
    return f"{md(dev['name'], 80)} ({handle})" if dev.get("name") else handle


def view(entry_id: str, entry: dict, state: store.State, base_url: str, raw_url: str) -> dict:
    record = state.lifecycle.get(entry_id) or {}
    health = state.health.get(entry_id) or store.default_health()
    owner, name = validate.parse_repo_url(entry["repo"])
    sha = health.get("scanned_commit") or ""
    verified = None
    rec = (state.verified.get("records") or {}).get(entry_id)
    if rec and rec.get("verified") and rec.get("repo_id") == record.get("repo_id"):
        verified = {"on": str(rec.get("verified_on")), "commit": rec.get("verified_commit"),
                    "updated_since": bool(sha and rec.get("verified_commit") != sha)}
    status = entry["status"]
    lic = health.get("license") or {"spdx": None, "kind": "none"}
    if lic.get("kind") == "open-source":
        license_label = lic.get("spdx") or "Open source"
    elif lic.get("kind") == "custom":
        license_label = f"Custom ({lic['spdx']})" if lic.get("spdx") else "Custom license"
    else:
        license_label = "No license stated"
    since = health.get("commits_since_scan")
    if health.get("scan_state") == "unknown" or since is None:
        since_text = "commits since unknown"
    else:
        since_text = f"{since} commit{'s' if since != 1 else ''} since"
    if health.get("scan_kind") == "curator-reviewed":
        scan_label = f"Reviewed by the curator {_date(health.get('scanned_at'))} · {since_text}"
    else:
        scan_label = f"Scanned {_date(health.get('scanned_at'))} · {since_text}"
    trust = (f"✔ Verified by trevorbilt on {verified['on']}" + (" (repo updated since)" if verified["updated_since"] else "")
             if verified else STATUS_LABEL[status])
    game = entry.get("game") or {}
    return {
        "id": entry_id,
        "entry": {**OPTIONAL, **entry},
        "name": entry["name"],
        "game_title": game.get("title", ""),
        "platform": game.get("original_platform"),
        "platform_label": PLATFORM_LABEL.get(game.get("original_platform") or "", ""),
        "year": game.get("original_release_year"),
        "repo": entry["repo"],
        "repo_owner": owner,
        "repo_name": name,
        "developer": developer_display(entry),
        "dev_github": (entry.get("developer") or {}).get("github"),
        "dev_name": (entry.get("developer") or {}).get("name"),
        "status": status,
        "status_label": STATUS_LABEL[status],
        "status_rank": STATUS_RANK[status],
        "verified": verified,
        "tier": "owner-verified" if verified else status,
        "trust": trust,
        "curator_own": bool(health.get("curator_own")),
        "health": health.get("health", "ok"),
        "health_label": "⚠ May have issues" if health.get("health") == "issues" else "OK",
        "failing_since": health.get("failing_since"),
        "license": lic,
        "license_label": license_label,
        "last_commit_date": health.get("last_commit_date"),
        "last_commit": _date(health.get("last_commit_date")),
        "archived": bool(health.get("archived")),
        "scanned_commit": sha,
        "scanned_at": health.get("scanned_at"),
        "scan_kind": health.get("scan_kind") or "automated",
        "commits_since": since,
        "scan_state": health.get("scan_state", "unknown"),
        "scan_label": scan_label,
        "github_verified": bool(health.get("github_verified")),
        "install_url": f"https://github.com/{owner}/{name}/blob/{sha}/AVP-INSTALL.md",
        "source_url": f"https://github.com/{owner}/{name}/tree/{sha}",
        "clone": f"git clone {entry['repo']} && cd {name} && git checkout {sha} && git submodule update --init --recursive",
        "page_url": f"{base_url}/ports/{entry_id}.md",
        "raw_page_url": f"{raw_url}/ports/{entry_id}.md",
        "inputs": ", ".join(INPUT_LABEL.get(i, i) for i in entry.get("input") or []),
        "experiences": ", ".join(EXPERIENCE_LABEL[k] for k in EXPERIENCE_LABEL if k in (entry.get("experiences") or [])),
        "sideload": "sideload" in (entry.get("install") or []),
        "listed_at": record.get("listed_at"),
        "changed_at": record.get("changed_at"),
        "media": None if entry.get("media") is False else media.feed_block(state.media.get(entry_id)),
    }


def sort_key(item: dict) -> tuple:
    last = item["last_commit_date"] or ""
    return (0 if item["verified"] else 1, item["status_rank"], _neg(last), item["id"])


def _neg(text: str) -> str:
    # sort ISO dates descending inside an ascending tuple sort
    return "".join(chr(0x10FFFF - ord(c)) for c in text)


def build_model(root: Path, repo_full: str) -> dict:
    policy = store.load_policy(root)
    brand = store.load_brand(root)
    state = store.State.load(root)
    entries, _errors = store.load_entries(root)
    base_url, raw_url = store.site_urls(policy, repo_full)
    listed, unavailable, tombstones = [], [], []
    for entry_id, record in sorted(state.lifecycle.items()):
        status = record.get("status")
        entry = entries.get(entry_id)
        if status == LISTED and entry and (state.health.get(entry_id) or {}).get("scanned_commit"):
            listed.append(view(entry_id, entry, state, base_url, raw_url))
        elif status == DECAY and entry:
            unavailable.append({
                "id": entry_id, "entry": entry, "name": entry.get("name", entry_id),
                "game_title": (entry.get("game") or {}).get("title", ""),
                "developer": developer_plain(entry),
                "credits": [{"name": c.get("name"), "role": c.get("role"), "url": c.get("url")}
                            for c in entry.get("credits") or []],
                "listed_at": record.get("listed_at"), "unavailable_since": record.get("changed_at"),
                "last_scanned_commit": (state.health.get(entry_id) or {}).get("scanned_commit"),
            })
        elif status in (PULLED, TAKEN_DOWN, WITHDRAWN):
            tombstones.append({"id": entry_id, "removed_at": record.get("changed_at")})
    listed.sort(key=sort_key)
    return {"policy": policy, "brand": brand, "brand_block": brand_block(root, brand),
            **brand_lines(brand), "base_url": base_url, "raw_url": raw_url, "repo_full": repo_full,
            "listed": listed, "unavailable": unavailable, "tombstones": tombstones}


