def feed(model: dict, generated_at: str) -> dict:
    brand = model["brand"]

    def credit(c: dict) -> dict:
        return {"name": c.get("name"), "role": c.get("role"), "url": c.get("url")}

    entries = []
    for v in model["listed"]:
        e = v["entry"]
        game = e.get("game") or {}
        dev = e.get("developer") or {}
        entries.append({
            "id": v["id"], "name": e["name"],
            "game": {"title": game.get("title"), "original_platform": game.get("original_platform"),
                     "original_release_year": game.get("original_release_year")},
            "repo_url": e["repo"], "source_ref": e.get("source_ref"), "source_url": v["source_url"],
            "install_doc_url": v["install_url"],
            "developer": {"name": dev.get("name"), "github": dev["github"], "url": dev.get("url"),
                          "github_verified": v["github_verified"]},
            "credits": [credit(c) for c in e.get("credits") or []],
            "upstream": list(e.get("upstream") or []),
            "self_reported_status": e["status"], "status_notes": e.get("status_notes"),
            "owner_verified": {"verified": bool(v["verified"]),
                               "verified_on": v["verified"]["on"] if v["verified"] else None,
                               "verified_commit": v["verified"]["commit"] if v["verified"] else None},
            "trust_tier": v["tier"], "curator_own": v["curator_own"],
            "health": {"status": v["health"], "failing_since": v["failing_since"]},
            "scanned_commit": v["scanned_commit"], "scanned_at": v["scanned_at"],
            "scan_kind": v["scan_kind"], "commits_since_scan": v["commits_since"],
            "scan_state": v["scan_state"], "archived": v["archived"],
            "last_commit_date": v["last_commit_date"], "license": v["license"],
            "visionos_min": e.get("visionos_min"), "input": list(e.get("input") or []),
            "experiences": [k for k in EXPERIENCE_LABEL if k in (e.get("experiences") or [])],
            "install": [k for k in ("build", "sideload") if k in (e.get("install") or ["build"])],
            "tags": list(e.get("tags") or []), "description": e.get("description"),
            "page_url": v["page_url"], "media": v["media"],
        })
    unavailable = [{
        "id": u["id"], "name": u["name"], "game": {"title": u["game_title"]},
        "developer": {"name": (u["entry"].get("developer") or {}).get("name"),
                      "github": (u["entry"].get("developer") or {}).get("github", "")},
        "credits": [credit(c) for c in u["credits"]],
        "listed_at": u["listed_at"], "unavailable_since": u["unavailable_since"],
        "last_scanned_commit": u["last_scanned_commit"],
    } for u in model["unavailable"]]
    return {
        "$schema": f"{model['raw_url']}/schema/feed-v1.schema.json",
        "schema_version": FEED_VERSION,
        "identifier": "com.trevorbilt.avp-ports-index",
        "generated_at": generated_at,
        "publisher": {"name": "trevorbilt", "curator": brand["curator_name"],
                      "github": brand["curator_github"], "url": brand["site"], "contact": brand["contact"]},
        "license": "CC0-1.0",
        "entries": entries,
        "unavailable": unavailable,
        "tombstones": model["tombstones"],
    }


def entry_fields_md(schema: dict) -> str:
    lines = [f"<!-- {GEN_NOTE} -->", "", "# Entry fields", "",
             "Every field allowed in `entries/<id>.yaml`. Anything else fails the schema check (S1-03).", "",
             "| Field | Required | Allowed values | Notes |", "| --- | --- | --- | --- |"]

    def constraint(prop: dict) -> str:
        if "$ref" in prop:
            return "https URL"
        if "enum" in prop:
            return ", ".join(f"`{v}`" for v in prop["enum"])
        if "const" in prop:
            return f"`{prop['const']}`"
        kind = prop.get("type", "")
        parts = []
        if kind == "string":
            if "pattern" in prop:
                parts.append(f"pattern `{prop['pattern']}`")
            if "minLength" in prop or "maxLength" in prop:
                parts.append(f"{prop.get('minLength', 0)} to {prop.get('maxLength', '∞')} characters")
        elif kind == "integer":
            parts.append(f"integer {prop.get('minimum')} to {prop.get('maximum')}")
        elif kind == "array":
            items = prop.get("items", {})
            inner = constraint(items) if items else ""
            parts.append(f"list{' of ' + inner if inner else ''}" + (f", at least {prop['minItems']}" if "minItems" in prop else "")
                         + (f", at most {prop['maxItems']}" if "maxItems" in prop else "")
                         + (f", must include `{prop['contains']['const']}`" if "const" in prop.get("contains", {}) else ""))
        elif kind == "object":
            parts.append("object")
        return "; ".join(parts) or kind

    def walk(props: dict, required: list, prefix: str) -> None:
        for key, prop in props.items():
            path = f"{prefix}{key}"
            desc = (prop.get("description") or "").replace("|", "\\|")
            lines.append(f"| `{path}` | {'yes' if key in required else 'no'} | {constraint(prop)} | {desc} |")
            if prop.get("type") == "object" and "properties" in prop:
                walk(prop["properties"], prop.get("required", []), f"{path}.")
            if prop.get("type") == "array" and isinstance(prop.get("items"), dict) and "properties" in prop["items"]:
                walk(prop["items"]["properties"], prop["items"].get("required", []), f"{path}[].")

    walk(schema["properties"], schema.get("required", []), "")
    lines += ["", "Missing optional fields are left out of the README and port pages, and are `null` (or empty lists) in the feed.", ""]
    return "\n".join(lines)


def checks_md() -> str:
    lines = [f"<!-- {GEN_NOTE} -->", "", "# Stage 1 checks", "",
             "These run on every entry PR, right away and for free. `scripts/preflight.py` runs the ones that "
             "don't need the index's own data. A **fail** is something to fix; a **route** means the curator "
             "looks before the PR goes further.", "",
             "| Check | What it checks | PR gate | Daily health check | Preflight |",
             "| --- | --- | --- | --- | --- |"]
    for func in checks.ALL_CHECKS:
        doc = " ".join(inspect.getdoc(func).split())
        check_id, _, rest = doc.partition(" · ")
        title, _, body = rest.partition(". ")
        gate = "yes"
        health = "yes" if check_id in checks.HEALTH_IDS else ""
        pre = "" if check_id in checks.PREFLIGHT_SKIPS else "yes"
        lines.append(f"| {check_id} {title} | {body.replace('|', '/')} | {gate} | {health} | {pre} |")
    lines.append("")
    return "\n".join(lines)


def preflight_source(root: Path) -> str:
    """A standalone copy of the Stage 1 checker for the submit skill."""
    pkg = root / "tools" / "avpindex"
    policy = store.load_policy(root)
    keep = {k: policy[k] for k in ("license_open_source", "license_route_phrases", "install_file",
                                   "forbidden_extensions", "archive_extensions", "large_blob_bytes",
                                   "release_binary_extensions")}
    schema = store.load_json("schema/entry.schema.json", root)

    def body(name: str) -> str:
        text = (pkg / name).read_text(encoding="utf-8")
        text = text.replace("from __future__ import annotations\n", "")
        return re.sub(r"^from \.[\w.]* import [^\n]*\n", "", text, flags=re.M)

    main = (pkg / "preflight_main.py").read_text(encoding="utf-8")
    main = main.replace("from __future__ import annotations\n", "")
    main = re.sub(r"^from \.[\w.]* import [^\n]*\n", "", main, flags=re.M)
    return "\n".join([
        "#!/usr/bin/env python3",
        f"# {GEN_NOTE}",
        "# Standalone copy of the AVP Ports Index Stage 1 checker (tools/avpindex/validate.py and checks.py).",
        "# Requires Python 3.11+ and: pip install pyyaml jsonschema requests",
        "from __future__ import annotations",
        "",
        f"POLICY = {pprint.pformat(keep, width=100, sort_dicts=False)}",
        f"SCHEMA = {pprint.pformat(schema, width=100, sort_dicts=False)}",
        "",
        "# ---- validate.py ----",
        body("validate.py"),
        "# ---- checks.py ----",
        body("checks.py"),
        "# ---- preflight ----",
        main,
    ])


def assert_brand(outputs: dict[str, str], model: dict) -> None:
    brand = model["brand"]
    readme = outputs["README.md"]
    for needle in (BRAND_START, BRAND_END, f"# {brand['display_name']}", model["curated_line"], model["footer"]):
        if needle not in readme:
            raise BrandError(f"README.md is missing its brand element: {needle[:40]}")
    for path, text in outputs.items():
        if path.startswith("ports/") and model["footer"] not in text:
            raise BrandError(f"{path} is missing the brand footer")
    llms = outputs["llms.txt"]
    if not llms.startswith("# AVP Ports Index\n") or brand["curator_name"] not in llms.split("\n\n")[1]:
        raise BrandError("llms.txt is missing its brand heading or curator")
    data = json.loads(outputs["feed/v1/index.json"])
    if data.get("publisher", {}).get("curator") != brand["curator_name"]:
        raise BrandError("feed is missing its publisher")


def render_all(root: Path, model: dict, generated_at: str) -> dict[str, str]:
    env = _env(root)
    out: dict[str, str] = {}
    ctx = dict(model, generated_at=generated_at)
    out["README.md"] = env.get_template("README.md.j2").render(**ctx)
    for v in model["listed"]:
        out[f"ports/{v['id']}.md"] = env.get_template("port.md.j2").render(v=v, **ctx)
    out["llms.txt"] = env.get_template("llms.txt.j2").render(**ctx)
    data = feed(model, generated_at)
    jsonschema.Draft202012Validator(store.load_json("schema/feed-v1.schema.json", root)).validate(data)
    out["feed/v1/index.json"] = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    schema = store.load_json("schema/entry.schema.json", root)
    out["skills/avp-index-submit/references/entry-fields.md"] = entry_fields_md(schema)
    out["skills/avp-index-submit/references/checks.md"] = checks_md()
    out["skills/avp-index-submit/scripts/preflight.py"] = preflight_source(root)
    return out


def previous_generated_at(root: Path) -> str | None:
    path = root / "feed/v1/index.json"
    if path.exists():
        try:
            return json.loads(path.read_text(encoding="utf-8")).get("generated_at")
        except ValueError:
            return None
    return None


def generate(root: Path | None = None, repo_full: str = "edgytoast/avp-ports-index",
             *, write: bool = True) -> dict[str, str]:
    """Render and (by default) write every surface. Returns {path: text}."""
    root = root or store.ROOT
    model = build_model(root, repo_full)
    previous = previous_generated_at(root)
    outputs = render_all(root, model, previous or store.iso(store.utcnow()))
    if previous and _differs(root, outputs):
        outputs = render_all(root, model, store.iso(store.utcnow()))
    assert_brand(outputs, model)
    if write:
        for path, text in outputs.items():
            store.write_text_if_changed(root / path, text)
        keep = {p for p in outputs if p.startswith("ports/")}
        for page in (root / "ports").glob("*.md"):
            if f"ports/{page.name}" not in keep:
                page.unlink()
        (root / "skills/avp-index-submit/scripts/preflight.py").chmod(0o755)
    return outputs


def _differs(root: Path, outputs: dict[str, str]) -> bool:
    for path, text in outputs.items():
        file = root / path
        if not file.exists() or file.read_text(encoding="utf-8") != text:
            return True
    expected = {p for p in outputs if p.startswith("ports/")}
    existing = {f"ports/{p.name}" for p in (root / "ports").glob("*.md")}
    return expected != existing
