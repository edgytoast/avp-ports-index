STATUS_LABEL = {
    "developer-verified": "Developer-verified",
    "working": "Working",
    "partially-working": "Partially working",
    "not-working": "Not working",
}
STATUS_RANK = {"developer-verified": 0, "working": 1, "partially-working": 2, "not-working": 3}
PLATFORM_LABEL = {
    "gamecube": "GameCube", "wii": "Wii", "n64": "Nintendo 64", "ps1": "PlayStation",
    "ps2": "PlayStation 2", "xbox": "Xbox", "dreamcast": "Dreamcast", "pc": "PC", "other": "Other",
}
INPUT_LABEL = {"game-controller": "game controller", "hand-tracking": "hand tracking",
               "keyboard-mouse": "keyboard and mouse"}
EXPERIENCE_LABEL = {"2d": "2D", "3d-immersive": "3D immersive", "3d-shared-space": "3D shared space",
                    "3d-tabletop": "3D tabletop", "6dof-immersive": "6DoF immersive", "6dof-progressive": "6DoF progressive"}
BRAND_START = "<!-- trevorbilt:brand:start -->"
BRAND_END = "<!-- trevorbilt:brand:end -->"
