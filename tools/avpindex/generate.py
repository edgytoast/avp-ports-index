"""Render every surface from the index's files (spec §10): README.md, ports/<id>.md,
feed/v1/index.json, llms.txt and the submit skill's generated files.

generate() reads only files and makes no API calls, so it runs without secrets and gives the
same output for the same files. generated_at moves only when other output changed.
"""

